/**
 * Planner - Coverage Target → TestPlan
 *
 * Three-level architecture:
 *   1. Deterministic Planner - Pure code, no LLM, for simple/known patterns
 *   2. Template Planner - Registry of UI pattern handlers
 *   3. LLM Planner - For complex/unknown/business logic
 *
 * Core principle:
 *   Planner decides "HOW to test", not "WHAT to test".
 *   "WHAT to test" is decided by CoverageModel + CoveragePolicy.
 *
 * Flow:
 *   CoverageTarget + Surface + Policy
 *         ↓
 *   PlannerSelector (risk + complexity + test type)
 *         ↓
 *   Deterministic / Template / LLM
 *         ↓
 *   TestPlan
 */

import type {
  CoverageModel,
  CoverageModule,
  CoverageSurface,
  CoverageFeature,
  CoverageTarget,
  CoveragePolicy,
  TestType,
  PriorityLevel,
  ScenarioType,
  FeatureType,
} from './coverage.js';
import {
  COVERAGE_POLICIES,
  effectivePriority,
  isFeatureCovered,
} from './coverage.js';
import type { SurfaceSignature } from './surface-signature.js';

// ─── TestPlan Types ──────────────────────────────────────────────────────────

/**
 * A single step in a test plan.
 * Richer than the old TestPlanItem - carries context for execution.
 */
export interface TestPlanStep {
  /** Human-readable description of what to do */
  description: string;
  /** The tool to use (browser_click, browser_fill_form, etc.) */
  tool?: string;
  /** Expected tool arguments (partial, will be filled at execution) */
  toolArgs?: Record<string, unknown>;
  /** What to verify after this step */
  expectedOutcome?: string;
  /** Which scenario this step serves */
  scenarioType?: ScenarioType;
}

/**
 * A test plan generated by a planner.
 * This is the OUTPUT of the planner, consumed by the execution engine.
 */
export interface TestPlan {
  /** Which surface this plan is for */
  surfaceKey: string;
  /** Which feature this plan targets */
  featureKey: string;
  /** Which scenario type this plan covers */
  scenarioType: ScenarioType;
  /** Which planner generated this */
  plannerLevel: 'deterministic' | 'template' | 'llm';
  /** The actual steps to execute */
  steps: TestPlanStep[];
  /** Priority of this plan */
  priority: PriorityLevel;
}

// ─── Planner Interface ───────────────────────────────────────────────────────

/**
 * Base planner interface.
 * All planners (Deterministic, Template, LLM) implement this.
 */
export interface Planner {
  /** Unique name for debugging/logging */
  name: string;

  /**
   * Can this planner handle the given target?
   * Called by PlannerSelector to choose the right planner.
   */
  canHandle(
    surface: CoverageSurface,
    feature: CoverageFeature,
    target: CoverageTarget,
    signature?: SurfaceSignature
  ): boolean;

  /**
   * Generate a test plan for the given target.
   * Returns steps that the execution engine will follow.
   */
  generate(
    surface: CoverageSurface,
    feature: CoverageFeature,
    target: CoverageTarget,
    policy: CoveragePolicy,
    signature?: SurfaceSignature
  ): TestPlan;
}

// ─── Risk Score ──────────────────────────────────────────────────────────────

/**
 * Calculate risk score for a surface/feature combination.
 * Used by PlannerSelector to choose the right planner level.
 *
 * Currently implemented factors:
 *   - Business Criticality (0-4) — from effectivePriority(module, surface, feature)
 *   - Data Mutation (0-3) — button/form/upload, higher for destructive actions
 *   - State Complexity (0-3) — form field count (only for feature.type === 'form')
 *   - Form Complexity (0-3) — complex field types (dropdown/upload/checkbox/radio)
 *   - Unknown (0-2) — feature.type === 'unknown'
 *
 * Not yet implemented (reserved for Phase 4 integration):
 *   - Navigation Depth (0-2) — requires workflow context
 *   - Dependency (0-2) — requires cross-surface analysis
 *
 * Note: State Complexity and Form Complexity may overlap for forms with many
 * complex fields. This is intentional — both dimensions contribute to risk.
 */
export function calculateRiskScore(
  surface: CoverageSurface,
  feature: CoverageFeature,
  module: CoverageModule
): number {
  let score = 0;

  // Business Criticality (0-4)
  const priority = effectivePriority(module, surface, feature);
  switch (priority) {
    case 'critical': score += 4; break;
    case 'high': score += 3; break;
    case 'normal': score += 1; break;
    case 'low': score += 0; break;
  }

  // Data Mutation (0-3)
  const mutationFeatures = ['button', 'form', 'upload'];
  if (mutationFeatures.includes(feature.type)) {
    // Check if it's a destructive action
    const destructiveKeywords = ['delete', 'remove', 'destroy', 'drop', 'clear', 'reset',
      '删除', '移除', '清除', '清空'];
    const name = feature.name.toLowerCase();
    if (destructiveKeywords.some(k => name.includes(k))) {
      score += 3;
    } else {
      score += 2;
    }
  }

  // State Complexity (0-3)
  // Forms with many fields have higher state complexity
  if (feature.type === 'form') {
    const fieldCount = surface.features.filter(f =>
      ['text-input', 'number-input', 'checkbox', 'radio', 'dropdown', 'upload'].includes(f.type)
    ).length;
    if (fieldCount > 10) score += 3;
    else if (fieldCount > 5) score += 2;
    else if (fieldCount > 0) score += 1;
  }

  // Form Complexity (0-3) - based on field types
  const complexFieldTypes = ['dropdown', 'upload', 'checkbox', 'radio'];
  const hasComplexFields = surface.features.some(f => complexFieldTypes.includes(f.type));
  if (hasComplexFields) {
    const complexCount = surface.features.filter(f => complexFieldTypes.includes(f.type)).length;
    if (complexCount > 5) score += 3;
    else if (complexCount > 2) score += 2;
    else score += 1;
  }

  // Navigation Depth (0-2) — not yet implemented, requires workflow context
  // Dependency (0-2) — not yet implemented, requires cross-surface analysis

  // Unknown (0-2) - if feature type is unknown
  if (feature.type === 'unknown') {
    score += 2;
  }

  return score;
}

// ─── Planner Selector ────────────────────────────────────────────────────────

/**
 * Select the appropriate planner based on risk, complexity, and test type.
 */
export function selectPlannerLevel(
  riskScore: number,
  featureType: FeatureType,
  testType: TestType
): 'deterministic' | 'template' | 'llm' {
  // Test type affects thresholds
  const thresholds: Record<TestType, { template: number; llm: number }> = {
    smoke:        { template: 4, llm: 8 },
    confirmation: { template: 3, llm: 6 },
    acceptance:   { template: 2, llm: 5 },
    full:         { template: 1, llm: 3 },
  };

  const t = thresholds[testType];

  // Feature types with a DETERMINISTIC plan — these always go deterministic
  // regardless of risk score, because the deterministic planner has a proper
  // real plan for them (not a placeholder). Forcing them through risk-score
  // logic would route them to template/llm when no template matches, which
  // was the exact bug that made text-input fall to the LLM stub.
  const deterministicTypes: FeatureType[] = [
    'link', 'tab', 'navigation',
    'checkbox', 'radio', 'pagination',
    'dropdown', 'button',
  ];
  if (deterministicTypes.includes(featureType)) {
    return 'deterministic';
  }

  // text-input/number-input have solid deterministic plans (type + verify).
  // They should only escalate to template/llm at genuinely high risk —
  // never by default, otherwise the most common element type falls through
  // to the LLM planner for no reason.
  if (featureType === 'text-input' || featureType === 'number-input') {
    if (riskScore < t.llm) return 'deterministic';
    return 'template';
  }

  // form / table / search / upload / modal — these genuinely benefit from
  // template specificity. Route to template by default.
  const templateTypes: FeatureType[] = ['form', 'table', 'search', 'upload', 'modal'];
  if (templateTypes.includes(featureType)) {
    return 'template';
  }

  // unknown — genuinely uncertain, only LLM can reason about it
  if (featureType === 'unknown') return 'llm';

  if (riskScore < t.template) return 'deterministic';
  if (riskScore < t.llm) return 'template';
  return 'llm';
}

// ─── Deterministic Planner ───────────────────────────────────────────────────

/**
 * Deterministic planner for simple, well-known patterns.
 * Pure code, no LLM, minimal cost.
 */
const deterministicPlanner: Planner = {
  name: 'deterministic',

  canHandle(surface, feature, target): boolean {
    // Handle simple interaction types + the most common element types
    // that have well-defined actions. The goal is to make the LLM planner
    // genuinely rare — only reached for 'unknown' features.
    const simpleTypes: FeatureType[] = [
      'link', 'tab', 'navigation',
      'checkbox', 'radio', 'pagination',
      'text-input', 'number-input',
      'dropdown',       // select option + verify
      'button',         // click + verify state change
    ];
    return simpleTypes.includes(feature.type);
  },

  generate(surface, feature, target): TestPlan {
    const steps: TestPlanStep[] = [];

    switch (feature.type) {
      case 'text-input':
      case 'number-input': {
        // The most common interactive element. Deterministic plan:
        // type a representative value → verify the value took effect.
        const value = feature.type === 'number-input' ? '123' : 'test-input-验证';
        steps.push({
          description: `Type "${value}" into "${feature.name}"`,
          tool: 'browser_type',
          toolArgs: { element: feature.name, text: value },
          expectedOutcome: 'Input accepted, value visible in field',
          scenarioType: target.scenarioType,
        });
        if (target.scenarioType === 'validation') {
          steps.push({
            description: `Clear "${feature.name}" and submit empty to verify required validation`,
            expectedOutcome: 'Validation error or graceful handling',
            scenarioType: 'validation',
          });
        } else if (target.scenarioType === 'boundary') {
          steps.push({
            description: `Type an extremely long string into "${feature.name}" to test limits`,
            tool: 'browser_type',
            expectedOutcome: 'Value truncated or accepted gracefully',
            scenarioType: 'boundary',
          });
        }
        break;
      }

      case 'link':
        steps.push({
          description: `Click link "${feature.name}" and verify navigation`,
          tool: 'browser_click',
          expectedOutcome: 'Page navigates to new URL or content changes',
          scenarioType: target.scenarioType,
        });
        break;

      case 'tab':
        steps.push({
          description: `Click tab "${feature.name}" and verify it becomes active`,
          tool: 'browser_click',
          expectedOutcome: `Tab "${feature.name}" is now selected/active`,
          scenarioType: target.scenarioType,
        });
        break;

      case 'navigation':
        steps.push({
          description: `Navigate via "${feature.name}" and verify destination`,
          tool: 'browser_click',
          expectedOutcome: 'Navigation succeeds, new page loads',
          scenarioType: target.scenarioType,
        });
        break;

      case 'checkbox':
        steps.push({
          description: `Toggle checkbox "${feature.name}" and verify state change`,
          tool: 'browser_check',
          expectedOutcome: `Checkbox "${feature.name}" state changes`,
          scenarioType: target.scenarioType,
        });
        break;

      case 'radio':
        steps.push({
          description: `Select radio button "${feature.name}" and verify selection`,
          tool: 'browser_click',
          expectedOutcome: `Radio button "${feature.name}" is selected`,
          scenarioType: target.scenarioType,
        });
        break;

      case 'pagination':
        if (target.scenarioType === 'normal') {
          steps.push({
            description: `Click next page and verify page change`,
            tool: 'browser_click',
            expectedOutcome: 'Page number changes, content updates',
            scenarioType: target.scenarioType,
          });
        } else if (target.scenarioType === 'boundary') {
          steps.push({
            description: `Navigate to first page, then last page, verify boundaries`,
            tool: 'browser_click',
            expectedOutcome: 'Boundary pages load correctly',
            scenarioType: target.scenarioType,
          });
        }
        break;

      case 'dropdown': {
        // A single dropdown select: open, pick an option, verify state change.
        // Validation for dropdown is rare; keep it to normal + boundary.
        steps.push({
          description: `Open "${feature.name}" and select an option`,
          tool: 'browser_select_option',
          expectedOutcome: 'Selected option visible, any dependent state updates',
          scenarioType: target.scenarioType,
        });
        if (target.scenarioType === 'boundary') {
          steps.push({
            description: `Select the first or last option in "${feature.name}" to check edge options`,
            tool: 'browser_select_option',
            expectedOutcome: 'Edge option accepted gracefully',
            scenarioType: 'boundary',
          });
        }
        break;
      }

      case 'button': {
        // Generic (non-CRUD) button. CRUD-named buttons are routed to crudTemplate
        // (template level, richer plan). Generic buttons get a simple click+verify.
        steps.push({
          description: `Click "${feature.name}" and observe resulting state change`,
          tool: 'browser_click',
          expectedOutcome: 'Button responded — page/dialog/state changed',
          scenarioType: target.scenarioType,
        });
        if (target.scenarioType === 'error') {
          steps.push({
            description: `Click "${feature.name}" twice rapidly and verify no double-submission or crash`,
            tool: 'browser_click',
            expectedOutcome: 'Double-click handled gracefully',
            scenarioType: 'error',
          });
        }
        break;
      }

      default:
        steps.push({
          description: `Interact with "${feature.name}" (${feature.type})`,
          scenarioType: target.scenarioType,
        });
    }

    return {
      surfaceKey: target.surfaceKey,
      featureKey: target.featureKey,
      scenarioType: target.scenarioType,
      plannerLevel: 'deterministic',
      steps,
      priority: target.priority.level,
    };
  },
};

// ─── Template Registry ───────────────────────────────────────────────────────

/**
 * Template planner interface.
 * Each template handles a specific UI pattern.
 */
export interface TemplatePlanner {
  name: string;
  canHandle(surface: CoverageSurface, feature: CoverageFeature, target: CoverageTarget): boolean;
  generate(surface: CoverageSurface, feature: CoverageFeature, target: CoverageTarget): TestPlan;
}

// ─── Form Template ───────────────────────────────────────────────────────────

const formTemplate: TemplatePlanner = {
  name: 'form',

  canHandle(surface, feature, _target): boolean {
    // Only handle feature.type === 'form'.
    // Button-type features (including CRUD buttons) are NOT handled here —
    // they are handled by crudTemplate or deterministicPlanner.
    return feature.type === 'form';
  },

  generate(surface, feature, target): TestPlan {
    const steps: TestPlanStep[] = [];

    if (target.scenarioType === 'normal') {
      // Fill all fields with valid data
      const formFields = surface.features.filter(f =>
        ['text-input', 'number-input', 'checkbox', 'radio', 'dropdown'].includes(f.type)
      );

      for (const field of formFields) {
        steps.push({
          description: `Fill "${field.name}" (${field.type}) with valid data`,
          tool: field.type === 'checkbox' ? 'browser_check' :
                field.type === 'radio' ? 'browser_click' :
                field.type === 'dropdown' ? 'browser_select_option' : 'browser_type',
          scenarioType: 'normal',
        });
      }

      // Find submit button
      const submitButton = surface.features.find(f =>
        f.type === 'button' && (
          /submit|提交|保存|确定|确认|create|创建|save/i.test(f.name)
        )
      );

      if (submitButton) {
        steps.push({
          description: `Click "${submitButton.name}" to submit`,
          tool: 'browser_click',
          expectedOutcome: 'Form submitted successfully',
          scenarioType: 'normal',
        });
      }

      steps.push({
        description: 'Verify submission result (success message or redirect)',
        expectedOutcome: 'Success indication visible',
        scenarioType: 'normal',
      });
    }

    if (target.scenarioType === 'validation') {
      // Test required field validation
      const requiredFields = surface.features.filter(f =>
        ['text-input', 'number-input', 'dropdown'].includes(f.type)
      );

      if (requiredFields.length > 0) {
        steps.push({
          description: 'Clear all required fields and submit',
          tool: 'browser_click',
          expectedOutcome: 'Validation errors shown for required fields',
          scenarioType: 'validation',
        });
      }

      // Test invalid formats
      for (const field of requiredFields.slice(0, 3)) {
        steps.push({
          description: `Enter invalid data in "${field.name}" and submit`,
          tool: 'browser_type',
          expectedOutcome: `Validation error for "${field.name}"`,
          scenarioType: 'validation',
        });
      }
    }

    if (target.scenarioType === 'boundary') {
      // Test boundary values
      const textFields = surface.features.filter(f => f.type === 'text-input');
      for (const field of textFields.slice(0, 2)) {
        steps.push({
          description: `Enter maximum length value in "${field.name}"`,
          tool: 'browser_type',
          expectedOutcome: 'Value accepted or length limit enforced',
          scenarioType: 'boundary',
        });
      }
    }

    if (target.scenarioType === 'error') {
      steps.push({
        description: 'Submit form with data that triggers server error',
        expectedOutcome: 'Error message displayed gracefully',
        scenarioType: 'error',
      });
    }

    return {
      surfaceKey: target.surfaceKey,
      featureKey: target.featureKey,
      scenarioType: target.scenarioType,
      plannerLevel: 'template',
      steps,
      priority: target.priority.level,
    };
  },
};

