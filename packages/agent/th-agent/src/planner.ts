// ─── Planner Selector (Main Entry Point) ─────────────────────────────────────

/**
 * All available planners in priority order.
 */
const PLANNERS: Planner[] = [
  deterministicPlanner,
  templatePlanner,
  llmPlanner,
];

/**
 * Generate a test plan for a coverage target.
 * This is the main entry point for Phase 3.
 *
 * Flow:
 *   1. Find the surface and feature from the model
 *   2. Calculate risk score
 *   3. Select planner level
 *   4. Generate plan
 */
export function generateTestPlan(
  model: CoverageModel,
  target: CoverageTarget,
  policy: CoveragePolicy,
  signature?: SurfaceSignature
): TestPlan | null {
  // Find the module, surface, and feature
  let targetModule: CoverageModule | undefined;
  let targetSurface: CoverageSurface | undefined;
  let targetFeature: CoverageFeature | undefined;

  for (const module of model.modules) {
    for (const surface of module.surfaces) {
      if (surface.key === target.surfaceKey) {
        targetModule = module;
        targetSurface = surface;
        targetFeature = surface.features.find(f => f.key === target.featureKey);
        break;
      }
    }
    if (targetSurface) break;
  }

  if (!targetModule || !targetSurface || !targetFeature) {
    return null;
  }

  // Calculate risk score
  const riskScore = calculateRiskScore(targetSurface, targetFeature, targetModule);

  // Use policy.testType directly instead of inferring from policy shape
  let plannerLevel = selectPlannerLevel(riskScore, targetFeature.type, policy.testType);

  // Specificity override: if a SPECIALIZED template pattern matches this feature,
  // prefer the template over the generic deterministic plan — templates
  // encode the full interaction flow (e.g. search: type → submit → verify).
  // The generic inputTemplate does NOT trigger the override: for a plain
  // text-input, the deterministic plan is equivalent and cheaper.
  if (plannerLevel === 'deterministic') {
    const matchingTemplate = TEMPLATE_PLANNERS.find(t =>
      t.name !== 'input' && t.canHandle(targetSurface, targetFeature, target)
    );
    if (matchingTemplate) {
      plannerLevel = 'template';
    }
  }

  // Find matching planner
  const planner = PLANNERS.find(p => {
    if (plannerLevel === 'deterministic') return p.name === 'deterministic';
    if (plannerLevel === 'template') return p.name === 'template';
    return p.name === 'llm';
  });

  if (!planner) {
    return null;
  }

  // Check if selected planner can handle it
  let plan: TestPlan;
  if (!planner.canHandle(targetSurface, targetFeature, target, signature)) {
    // Fall back to template
    const fallback = PLANNERS.find(p => p.name === 'template');
    if (fallback?.canHandle(targetSurface, targetFeature, target, signature)) {
      plan = fallback.generate(targetSurface, targetFeature, target, policy, signature);
    } else {
      // Fall back to LLM
      plan = llmPlanner.generate(targetSurface, targetFeature, target, policy, signature);
    }
  } else {
    plan = planner.generate(targetSurface, targetFeature, target, policy, signature);
  }

  // Validate the plan — if invalid (e.g. empty steps), fall back to LLM
  if (!validateTestPlan(plan)) {
    plan = llmPlanner.generate(targetSurface, targetFeature, target, policy, signature);
  }

  return plan;
}

/**
 * Generate test plans for ALL uncovered targets.
 *
 * ⚠️ This is a DEBUG / PREVIEW tool, NOT the runtime main path.
 * Runtime should use: selectNextTarget() → generateTestPlan() one at a time.
 * This function exists for:
 *   - Debugging: see what plans would be generated
 *   - Preview: estimate total test scope
 *   - Testing: verify planner behavior across multiple targets
 */
export function generateAllPlans(
  model: CoverageModel,
  policy: CoveragePolicy,
  signatures?: Map<string, SurfaceSignature>
): TestPlan[] {
  const plans: TestPlan[] = [];

  for (const module of model.modules) {
    for (const surface of module.surfaces) {
      for (const feature of surface.features) {
        for (const [scenarioType, coverage] of Object.entries(feature.scenarios) as [ScenarioType, import('./coverage.js').ScenarioCoverage][]) {
          if (coverage.status === 'not_applicable' || coverage.status === 'tested') {
            continue;
          }

          const isRequired = policy.scenarioDepth[scenarioType] === 'required';
          // Use effectivePriority (module → surface → feature max), not just feature.priority
          const effPriority = effectivePriority(module, surface, feature);
          const isCritical = effPriority === 'critical' && policy.risk.criticalFeaturesAlwaysRequired;

          if (isRequired || isCritical) {
            const target: CoverageTarget = {
              surfaceKey: surface.key,
              featureKey: feature.key,
              scenarioType,
              priority: {
                level: effPriority,
                source: feature.priority.source,
              },
            };

            const signature = signatures?.get(surface.key);
            const plan = generateTestPlan(model, target, policy, signature);
            if (plan && validateTestPlan(plan)) {
              plans.push(plan);
            }
          }
        }
      }
    }
  }

  // Sort by priority
  const priorityOrder: Record<PriorityLevel, number> = { critical: 4, high: 3, normal: 2, low: 1 };
  plans.sort((a, b) => priorityOrder[b.priority] - priorityOrder[a.priority]);

  return plans;
}

// ─── Plan Validation ─────────────────────────────────────────────────────────

/**
 * Validate a generated TestPlan.
 * Returns true if the plan is valid and executable.
 * Returns false if the plan is empty or malformed.
 *
 * Checks:
 *   - steps.length > 0
 *   - Every step has a non-empty description
 *   - scenarioType matches across all steps
 *   - plannerLevel is a valid value
 */
export function validateTestPlan(plan: TestPlan): boolean {
  // Must have at least one step
  if (plan.steps.length === 0) return false;

  // Every step must have a description
  if (plan.steps.some(s => !s.description || s.description.trim().length === 0)) return false;

  // scenarioType must be consistent
  const validScenarios: ScenarioType[] = ['normal', 'validation', 'boundary', 'error', 'lifecycle'];
  if (!validScenarios.includes(plan.scenarioType)) return false;

  // plannerLevel must be valid
  const validLevels = ['deterministic', 'template', 'llm'];
  if (!validLevels.includes(plan.plannerLevel)) return false;

  return true;
}

